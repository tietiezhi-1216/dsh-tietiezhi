import { readFile, writeFile } from 'node:fs/promises';

const source = (path) => readFile(new URL(path, import.meta.url), 'utf8');
const output = new URL('../client.js', import.meta.url);
const modules = await Promise.all([
  source('../features/permanent-delete/browser.js'),
]);
const indent = (text) => text.trimEnd().split('\n').map((line) => line ? `    ${line}` : '').join('\n');
const bundle = `// Generated by npm run build; edit the browser modules instead.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-tietiezhi',\n  factory(require) {\n    const React = require('react');\n${modules.map(indent).join('\n\n')}\n    return { inject: ['contextMenus', 'locale', 'slots', 'remoteAccess'], apply: permanentDeleteModule(React) };\n  },\n});\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== bundle) throw new Error('Run npm run build to regenerate client.js');
} else {
  await writeFile(output, bundle);
}
